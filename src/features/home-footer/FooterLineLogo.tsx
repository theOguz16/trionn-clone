const FOOTER_SCALE = [
  130.81,
  146.83,
  164.81,
  196,
  220,
  261.63,
  293.66,
] as const;

function createLinePath(
  segment: Segment,
  amplitude = 0,
  phase = 0,
) {
  const [x1, y1, x2, y2] = segment;
  const pointCount = 26;
  const points = Array.from(
    { length: pointCount },
    (_, index) => {
      const progress = index / (pointCount - 1);
      const edgeEnvelope = Math.sin(Math.PI * progress);
      const wave =
        Math.sin(progress * Math.PI * 3.2 + phase) *
        edgeEnvelope *
        amplitude;

      return [
        x1 + (x2 - x1) * progress,
        y1 + (y2 - y1) * progress + wave,
      ] as const;
    },
  );

  return points
    .map(([x, y], index) =>
      `${index === 0 ? "M" : "L"} ${x.toFixed(3)} ${y.toFixed(3)}`,
    )
    .join(" ");
}

function FooterLineSegment({
  segment,
  index,
}: {
  segment: Segment;
  index: number;
}) {
  const visiblePathRef = useRef<SVGPathElement>(null);
  const animationFrameRef = useRef<number | null>(null);
  const basePath = createLinePath(segment);

  useEffect(
    () => () => {
      if (animationFrameRef.current !== null) {
        window.cancelAnimationFrame(animationFrameRef.current);
      }
    },
    [],
  );

  const playLine = () => {
    const visiblePath = visiblePathRef.current;
    if (!visiblePath) return;

    if (animationFrameRef.current !== null) {
      window.cancelAnimationFrame(animationFrameRef.current);
    }

    const note = FOOTER_SCALE[index % FOOTER_SCALE.length];
    const octave = Math.floor((index % 21) / FOOTER_SCALE.length);
    const frequency = note * Math.pow(2, octave * 0.5);
    const strength = 0.56 + (index % 4) * 0.06;

    audioManager.playFooterNote(frequency, strength, 0.78);
    window.dispatchEvent(
      new CustomEvent("trionn:footer-note", {
        detail: { strength },
      }),
    );

    if (window.matchMedia("(prefers-reduced-motion: reduce)").matches) {
      return;
    }

    const startedAt = window.performance.now();
    const duration = 680;

    const animate = (now: number) => {
      const progress = Math.min(1, (now - startedAt) / duration);
      const attack = Math.min(1, progress / 0.1);
      const decay = Math.pow(1 - progress, 2.1);
      const amplitude = 8.5 * attack * decay;

      visiblePath.setAttribute(
        "d",
        createLinePath(
          segment,
          amplitude,
          progress * Math.PI * 7 + index * 0.37,
        ),
      );

      if (progress < 1) {
        animationFrameRef.current = window.requestAnimationFrame(animate);
      } else {
        visiblePath.setAttribute("d", basePath);
        animationFrameRef.current = null;
      }
    };

    animationFrameRef.current = window.requestAnimationFrame(animate);
  };

  return (
    <g
      data-footer-line={index}
      className={styles.lineSegment}
      onPointerEnter={playLine}
      onFocus={playLine}
    >
      <path
        ref={visiblePathRef}
        d={basePath}
        className={styles.visibleLine}
      />
      <path d={basePath} className={styles.hitLine} />
    </g>
  );
}

